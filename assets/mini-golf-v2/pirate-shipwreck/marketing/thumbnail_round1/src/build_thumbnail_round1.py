# build_thumbnail_round1.py - Pirate ship thumbnail ROUND 1 (A hero / B octopus / C adventure) as real 3D scenes.
#
# Run from the job root (one Blender process at a time; see out/README.md):
#   blender -b inputs/start_ship_whimsy_v5_1.blend --python-exit-code 1 --python out/src/build_thumbnail_round1.py -- \
#       --kit1 out/build/kit_v1_geom --kit22 out/build/kit_v22_geom --output out/pirate_thumbnail_round1.blend
# All paths default to script-relative locations (out/ = this file's parent's parent).
#
# What it does
#  * The approved ship .blend is opened and NEVER saved over (save_as copy to --output). Ship meshes, materials,
#    modifiers and object transforms are not edited. Only render visibility of helper empties is turned off and the
#    Collision collection is simply not linked into the thumbnail scenes.
#  * Adds a RENDER_ONLY staged tropical cove (NOT the game layout): faceted sand terrain with a shallow lagoon,
#    transparent turquoise water surface with restrained bump waves, sky world, and ORIGINAL kit palm/rock/fern meshes
#    regenerated by the untouched kit_v1 / kit_v22 generators (geometry JSON -> Blender meshes, palette texture).
#  * Creates 3 scenes sharing the same ship + environment collections, each with its own saved camera and sun:
#    Thumbnail_A_Hero, Thumbnail_B_Octopus, Thumbnail_C_Adventure. Per-scene extra dressing collections are allowed.
#  * Packs all images and writes out/build/build_report.json (consumed by validate_round1.py -> manifest.json).
