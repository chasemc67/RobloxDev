def kit_material(name, png):
    img = bpy.data.images.load(png, check_existing=True)
    img.name = name + '_palette.png'
    m = bpy.data.materials.new(name); m.use_nodes = True; nt = m.node_tree
    bs = next(n for n in nt.nodes if n.type == 'BSDF_PRINCIPLED')
    ti = nt.nodes.new('ShaderNodeTexImage'); ti.image = img; ti.interpolation = 'Closest'
    nt.links.new(ti.outputs['Color'], bs.inputs['Base Color'])
    bs.inputs['Roughness'].default_value = 0.6
    return m


def B(v):  # kit Roblox frame (+Y up, front +Z) -> Blender (Z up). Same mapping as the original build_kit.py
    return (v[0], -v[2], v[1])


_KITMESH = {}


def kit_mesh(geom_dir, pid, mat, part_filter=None):
    key = (geom_dir, pid)
    if key in _KITMESH: return _KITMESH[key]
    g = json.load(open(os.path.join(geom_dir, 'geom', pid + '.json')))[pid]
    objs = [o for o in g['objects'] if part_filter is None or o['name'] == pid]
    V = []; T = []; U = []; S = []; n = 0
    for o in objs:
        V += [B(v) for v in o['verts']]; T += [[a + n, b + n, c + n] for a, b, c in o['tris']]; U += o['uvs']; S += o['smooth']; n += len(o['verts'])
    me = bpy.data.meshes.new('KIT_' + pid)
    me.from_pydata(V, [], T); me.validate(); me.update()
    uv = me.uv_layers.new(name='UVMap')
    for l in me.loops: uv.data[l.index].uv = U[l.vertex_index]
    for p, sm in zip(me.polygons, S): p.use_smooth = bool(sm)
    # consistent outward normals per island (the original pipeline relied on trimesh.fix_normals)
    bm = bmesh.new(); bm.from_mesh(me); bmesh.ops.recalc_face_normals(bm, faces=bm.faces); bm.to_mesh(me); bm.free()
    me.materials.append(mat)
    _KITMESH[key] = me
    return me


PLACED = []


def place(coll, me, pid, x, y, s=1.0, yaw=0.0, sink=0.0, kit='kit_v1', z=None):
    ob = bpy.data.objects.new('RO_%s_%03d' % (pid, len(PLACED)), me)
    gz = float(height(x, y)) if z is None else z
    ob.location = (x, y, gz - sink * s)
    ob.rotation_euler = (0, 0, math.radians(yaw))
    ob.scale = (s, s, s)
    coll.objects.link(ob)
    PLACED.append(dict(object=ob.name, prop=pid, kit=kit, collection=coll.name, loc=[round(x, 1), round(y, 1), round(ob.location.z, 2)],
                       scale=s, yaw=yaw, tris=len(me.polygons)))
    return ob


