def new_coll(name, parent):
    c = bpy.data.collections.new(name); parent.children.link(c); return c


def cam_obj(name, loc, target, lens, roll=0.0):
    cd = bpy.data.cameras.new(name); cd.lens = lens; cd.sensor_fit = 'HORIZONTAL'; cd.sensor_width = 36.0
    cd.clip_start = 0.5; cd.clip_end = 30000.0
    ob = bpy.data.objects.new(name, cd); ob.location = Vector(loc)
    q = (Vector(target) - Vector(loc)).to_track_quat('-Z', 'Y')
    ob.rotation_euler = (q @ Matrix.Rotation(math.radians(roll), 4, 'Z').to_quaternion()).to_euler() if roll else q.to_euler()
    ob.matrix_world = Matrix.LocRotScale(ob.location, ob.rotation_euler, Vector((1, 1, 1)))  # valid before depsgraph eval (framing report)
    return ob


def sun_obj(name, az_from, elev, strength, rgb, angle=2.0, shadow=True):
    sd = bpy.data.lights.new(name, 'SUN'); sd.energy = strength; sd.color = lin(rgb); sd.angle = math.radians(angle); sd.use_shadow = shadow
    ob = bpy.data.objects.new(name, sd)
    if not shadow:
        ob.visible_glossy = False   # fill must not draw a specular streak on the water
    el, az = math.radians(elev), math.radians(az_from)
    to_sun = Vector((math.cos(el) * math.cos(az), math.cos(el) * math.sin(az), math.sin(el)))
    ob.rotation_euler = (-to_sun).to_track_quat('-Z', 'Y').to_euler()
    return ob


def make_world():
    w = bpy.data.worlds.new('RO_TropicalSky'); w.use_nodes = True; nt = w.node_tree
    bg = next(n for n in nt.nodes if n.type == 'BACKGROUND')
    tc = nt.nodes.new('ShaderNodeTexCoord'); sep = nt.nodes.new('ShaderNodeSeparateXYZ')
    nt.links.new(tc.outputs['Generated'], sep.inputs[0])
    r = ramp_node(nt, [(0.0, (196, 228, 246)), (0.08, (150, 205, 240)), (0.35, (88, 164, 230)), (1.0, (62, 132, 214))])
    nt.links.new(sep.outputs['Z'], r.inputs['Fac'])
    nt.links.new(r.outputs['Color'], bg.inputs['Color']); bg.inputs['Strength'].default_value = 1.0
    return w


def setup_render(sc, cam, samples):
    sc.camera = cam
    try:
        sc.render.engine = 'CYCLES'
    except TypeError as e:
        raise SystemExit('Cycles unavailable: %s' % e)
    cy = sc.cycles
    cy.device = 'CPU'          # Roblox Studio is open on this PC -> CPU only
    cy.samples = samples; cy.use_adaptive_sampling = True; cy.adaptive_threshold = 0.02
    cy.use_denoising = True
    try: cy.denoiser = 'OPENIMAGEDENOISE'
    except TypeError: pass
    cy.max_bounces = 8; cy.diffuse_bounces = 3; cy.glossy_bounces = 2; cy.transmission_bounces = 4; cy.transparent_max_bounces = 16
    cy.caustics_reflective = False; cy.caustics_refractive = False
    cy.blur_glossy = 1.0
    sc.render.resolution_x, sc.render.resolution_y = RES; sc.render.resolution_percentage = 100
    sc.render.film_transparent = False
    vs = sc.view_settings; vs.view_transform = 'Standard'; vs.look = 'None'; vs.gamma = 1.0
    sc.display_settings.display_device = 'sRGB'
    im = sc.render.image_settings; im.file_format = 'PNG'; im.color_mode = 'RGB'; im.color_depth = '8'


def proj(sc, cam, p):
    v = world_to_camera_view(sc, cam, Vector(p))
    return (round(v.x, 3), round(v.y, 3), round(v.z, 1))


def obj_bbox(names):
    mn = Vector((1e9,) * 3); mx = Vector((-1e9,) * 3)
    for nm in names:
        o = bpy.data.objects[nm]
        for c in o.bound_box:
            w = o.matrix_world @ Vector(c)
            for i in range(3): mn[i] = min(mn[i], w[i]); mx[i] = max(mx[i], w[i])
    return mn, mx


def extreme_vertex(names, axis, sign=1):
    best = None
    for nm in names:
        o = bpy.data.objects[nm]; M = o.matrix_world
        for v in o.data.vertices:
            w = M @ v.co
            if best is None or sign * w[axis] > sign * best[axis]: best = w.copy()
    return best


def frame_report(sc, cam, ship_vis):
    """projected extents (0..1 frame coords, y up) of the ship + key points"""
    xs, ys = [], []
    for nm in ship_vis:
        o = bpy.data.objects[nm]
        if o.type != 'MESH': continue
        M = o.matrix_world
        vs = o.data.vertices
        step = max(1, len(vs) // 400)
        for i in range(0, len(vs), step):
            u = world_to_camera_view(sc, cam, M @ vs[i].co)
            if u.z > 0: xs.append(u.x); ys.append(u.y)
    bx, by = [], []
    for nm in ship_vis:   # every vertex of the bow end (x > 140) incl. bowsprit, figurehead octopus, bow eyes
        o = bpy.data.objects[nm]
        if o.type != 'MESH': continue
        M = o.matrix_world
        for v in o.data.vertices:
            w = M @ v.co
            if w.x > 140:
                u = world_to_camera_view(sc, cam, w)
                if u.z > 0: bx.append(u.x); by.append(u.y)
    r = dict(ship_u=[round(min(xs), 3), round(max(xs), 3)], ship_v=[round(min(ys), 3), round(max(ys), 3)])
    if bx: r.update(bow_u=[round(min(bx), 3), round(max(bx), 3)], bow_v=[round(min(by), 3), round(max(by), 3)])
    return r


