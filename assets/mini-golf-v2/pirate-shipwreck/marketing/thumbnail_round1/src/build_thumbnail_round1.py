WATER_Z = 1.0          # lagoon / sea surface height (ship hull bottom is z=-2.1, so the keel sits ~3 studs deep)


def ell(x, y, cx, cy, rx, ry):
    return 1.0 - ((x - cx) / rx) ** 2 - ((y - cy) / ry) ** 2


def height(x, y):
    """Staged cove height field (Blender Z-up studs). Vectorised over numpy arrays."""
    x = np.asarray(x, float); y = np.asarray(y, float)
    e1 = ell(x, y, 60, -340, 430, 235)      # foreground beach (camera side, -Y)
    e2 = ell(x, y, 310, -50, 195, 265)      # bow beach (+X), octopus stands over it
    e3 = ell(x, y, 265, 175, 235, 150)      # rear-right jungle mound
    e4 = ell(x, y, -330, -330, 150, 110)    # small spit far left (B background palms)
    f = np.maximum.reduce([e1, e2, e3, e4])
    z = -3.2 + 7.2 * smoothstep(-0.25, 0.35, f)                       # beach slope: waterline at f~0.05
    z = np.where(f < -0.25, -3.2 - 24.0 * smoothstep(-0.25, -0.9, f), z)  # drop-off to deep sea
    z += 15.0 * smoothstep(0.30, 0.90, e3)                            # mound
    # shallow lagoon shelf around ship / pier: seabed never deeper than ~-4 inside it
    fs = ell(x, y, -40, -40, 280, 165)
    shelf = -3.8 - 23.0 * (1.0 - smoothstep(0.0, 0.45, fs))
    z = np.maximum(z, shelf)
    # pool in front of the hull (between camera and port side) + seat under the hull
    fp = ell(x, y, 15, -88, 178, 50)
    z = z * (1 - smoothstep(0.0, 0.40, fp)) + (-2.4) * smoothstep(0.0, 0.40, fp)
    fh = np.minimum(smoothstep(-175, -150, x) * (1 - smoothstep(150, 185, x)), smoothstep(-80, -55, y) * (1 - smoothstep(30, 55, y)))
    z = z * (1 - fh) + np.minimum(z, -1.5) * fh
    # gentle dunes on dry land
    dry = smoothstep(1.5, 3.5, z)
    z += dry * (0.9 * np.sin(x * 0.031 + 1.3) * np.sin(y * 0.027 + 0.4) + 0.5 * np.sin(x * 0.07 - y * 0.05))
    return z


def build_terrain(coll):
    x0, x1, y0, y1, cell = -760.0, 960.0, -900.0, 660.0, 7.0
    nx, ny = int((x1 - x0) / cell), int((y1 - y0) / cell)
    xs = np.linspace(x0, x1, nx + 1); ys = np.linspace(y0, y1, ny + 1)
    X, Y = np.meshgrid(xs, ys, indexing='ij')
    rng = np.random.default_rng(7)
    X = X + rng.uniform(-1.8, 1.8, X.shape); Y = Y + rng.uniform(-1.8, 1.8, Y.shape)
    Z = height(X, Y) + rng.uniform(-0.3, 0.3, X.shape)
    V = np.stack([X.ravel(), Y.ravel(), Z.ravel()], 1)
    idx = np.arange((nx + 1) * (ny + 1)).reshape(nx + 1, ny + 1)
    a = idx[:-1, :-1].ravel(); b = idx[1:, :-1].ravel(); c = idx[1:, 1:].ravel(); d = idx[:-1, 1:].ravel()
    flip = (rng.random(a.shape) < 0.5)
    t1 = np.where(flip[:, None], np.stack([a, b, c], 1), np.stack([a, b, d], 1))
    t2 = np.where(flip[:, None], np.stack([a, c, d], 1), np.stack([b, c, d], 1))
    F = np.concatenate([t1, t2])
    me = bpy.data.meshes.new('RO_CoveTerrain')
    me.from_pydata(V.tolist(), [], F.tolist())
    me.validate(); me.update()
    for p in me.polygons: p.use_smooth = False
    ob = bpy.data.objects.new('RO_CoveTerrain', me)
    coll.objects.link(ob)
    me.materials.append(mat_sand())
    # far sea floor beyond the terrain patch
    fl = add_plane('RO_SeaFloorFar', 30000, (0, 0, -27.5), coll)
    fl.data.materials.append(mat_sand())
    return ob


def add_plane(name, size, loc, coll):
    me = bpy.data.meshes.new(name)
    s = size / 2
    me.from_pydata([(-s, -s, 0), (s, -s, 0), (s, s, 0), (-s, s, 0)], [], [(0, 1, 2, 3)])
    ob = bpy.data.objects.new(name, me); ob.location = loc; coll.objects.link(ob)
    return ob


def ramp_node(nt, stops):
    r = nt.nodes.new('ShaderNodeValToRGB')
    els = r.color_ramp.elements
    while len(els) > 1: els.remove(els[-1])
    for i, (pos, rgb) in enumerate(stops):
        e = els[0] if i == 0 else els.new(pos)
        e.position = pos; e.color = lin(rgb, 1.0)
    return r


_MATS = {}


def mat_sand():
    if 'sand' in _MATS: return _MATS['sand']
    m = bpy.data.materials.new('RO_Sand_Seabed'); m.use_nodes = True; nt = m.node_tree
    bs = next(n for n in nt.nodes if n.type == 'BSDF_PRINCIPLED')
    geo = nt.nodes.new('ShaderNodeNewGeometry'); sep = nt.nodes.new('ShaderNodeSeparateXYZ')
    nt.links.new(geo.outputs['Position'], sep.inputs[0])
    mr = nt.nodes.new('ShaderNodeMapRange'); mr.inputs['From Min'].default_value = -28.0; mr.inputs['From Max'].default_value = 22.0
    nt.links.new(sep.outputs['Z'], mr.inputs['Value'])
    # height (z) -> colour: deep sea blue / lagoon turquoise seabed / wet sand / golden sand / jungle green on the mound
    def zp(z): return (z + 28.0) / 50.0
    rp = ramp_node(nt, [(zp(-27), (18, 70, 140)), (zp(-14), (26, 110, 170)), (zp(-5.5), (40, 170, 190)),
                        (zp(-2.6), (70, 205, 200)), (zp(-0.6), (150, 226, 206)), (zp(0.55), (236, 228, 196)),
                        (zp(1.3), (222, 186, 122)), (zp(3.0), (236, 196, 128)), (zp(8.5), (226, 188, 120)),
                        (zp(10.0), (110, 170, 74)), (zp(22), (86, 150, 64))])
    nt.links.new(mr.outputs['Result'], rp.inputs['Fac'])
    nz = nt.nodes.new('ShaderNodeTexNoise'); nz.inputs['Scale'].default_value = 0.035; nz.inputs['Detail'].default_value = 1.0
    nt.links.new(geo.outputs['Position'], nz.inputs['Vector'])
    mx = nt.nodes.new('ShaderNodeMix'); mx.data_type = 'RGBA'; mx.blend_type = 'MULTIPLY'
    mx.inputs['Factor'].default_value = 1.0
    cr = nt.nodes.new('ShaderNodeMapRange'); cr.inputs['From Min'].default_value = 0.3; cr.inputs['From Max'].default_value = 0.7
    cr.inputs['To Min'].default_value = 0.92; cr.inputs['To Max'].default_value = 1.06
    nt.links.new(nz.outputs['Fac'], cr.inputs['Value'])
    cmb = nt.nodes.new('ShaderNodeCombineColor')
    for i in range(3): nt.links.new(cr.outputs['Result'], cmb.inputs[i])
    nt.links.new(rp.outputs['Color'], mx.inputs['A']); nt.links.new(cmb.outputs['Color'], mx.inputs['B'])
    nt.links.new(mx.outputs['Result'], bs.inputs['Base Color'])
    bs.inputs['Roughness'].default_value = 0.85
    _MATS['sand'] = m
    return m


def mat_water():
    m = bpy.data.materials.new('RO_Water_Shallow'); m.use_nodes = True; nt = m.node_tree
    for n in list(nt.nodes):
        if n.type != 'OUTPUT_MATERIAL': nt.nodes.remove(n)
    out = next(n for n in nt.nodes if n.type == 'OUTPUT_MATERIAL')
    tr = nt.nodes.new('ShaderNodeBsdfTransparent'); tr.inputs['Color'].default_value = lin((214, 246, 246), 1.0)
    df = nt.nodes.new('ShaderNodeBsdfDiffuse'); df.inputs['Color'].default_value = lin((70, 190, 205), 1.0)
    gl = nt.nodes.new('ShaderNodeBsdfGlossy'); gl.inputs['Roughness'].default_value = 0.22   # soft: no blown sun glint
    gl.inputs['Color'].default_value = (0.85, 0.93, 1.0, 1)
    # restrained waves: small bump from two noise scales
    tc = nt.nodes.new('ShaderNodeTexCoord')
    n1 = nt.nodes.new('ShaderNodeTexNoise'); n1.inputs['Scale'].default_value = 0.06; n1.inputs['Detail'].default_value = 3.0
    nt.links.new(tc.outputs['Object'], n1.inputs['Vector'])
    bump = nt.nodes.new('ShaderNodeBump'); bump.inputs['Strength'].default_value = 0.22; bump.inputs['Distance'].default_value = 0.6
    nt.links.new(n1.outputs['Fac'], bump.inputs['Height'])
    nt.links.new(bump.outputs['Normal'], gl.inputs['Normal'])
    body = nt.nodes.new('ShaderNodeMixShader'); body.inputs['Fac'].default_value = 0.16   # 16% turquoise body colour
    nt.links.new(tr.outputs[0], body.inputs[1]); nt.links.new(df.outputs[0], body.inputs[2])
    lw = nt.nodes.new('ShaderNodeLayerWeight'); lw.inputs['Blend'].default_value = 0.18
    nt.links.new(bump.outputs['Normal'], lw.inputs['Normal'])
    fm = nt.nodes.new('ShaderNodeMath'); fm.operation = 'MULTIPLY'; fm.inputs[1].default_value = 0.45
    nt.links.new(lw.outputs['Fresnel'], fm.inputs[0])
    mix = nt.nodes.new('ShaderNodeMixShader')
    nt.links.new(fm.outputs[0], mix.inputs['Fac']); nt.links.new(body.outputs[0], mix.inputs[1]); nt.links.new(gl.outputs[0], mix.inputs[2])
    nt.links.new(mix.outputs[0], out.inputs['Surface'])
    return m


def build_water(coll):
    me = bpy.data.meshes.new('RO_WaterSurface')
    bm = bmesh.new()
    bmesh.ops.create_grid(bm, x_segments=1, y_segments=1, size=15000)
    bm.to_mesh(me); bm.free()
    ob = bpy.data.objects.new('RO_WaterSurface', me); ob.location = (0, 0, WATER_Z); coll.objects.link(ob)
    me.materials.append(mat_water())
    ob.visible_shadow = False   # sunlight reaches the seabed (transparent shading still tints it)
    return ob


