"""Contact sheet + README.md from manifest.json (run with system python3; needs Pillow)."""
import json, os
from PIL import Image, ImageDraw, ImageFont

SRC = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.dirname(SRC)
man = json.load(open(os.path.join(OUT, "manifest.json")))
props = man["props"]

# ----------------------------------------------------------------------------- contact sheet
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
FONT_R = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
f1 = ImageFont.truetype(FONT, 15)
f2 = ImageFont.truetype(FONT_R, 12)
show = [p for p in props if not (p["group"] == "tee_sign" and p["name"] != "tee_sign_h01")]
CW = 200
cols = 4
cell_w, cell_h = CW * 2 + 12, CW + 48
rows = (len(show) + cols - 1) // cols
sheet = Image.new("RGB", (cols * cell_w + 12, rows * cell_h + 60), (24, 26, 30))
d = ImageDraw.Draw(sheet)
d.text((14, 14), f"Lantern Grove props: {len(props)} meshes ({len(show)} shown; tee signs h02-h09 omitted)", font=ImageFont.truetype(FONT, 22),
       fill=(242, 182, 50))
for i, p in enumerate(show):
    x0 = 12 + (i % cols) * cell_w
    y0 = 56 + (i // cols) * cell_h
    for j, v in enumerate(("eye", "34")):
        fp = os.path.join(OUT, "previews", f"{p['name']}_{v}.png")
        if os.path.exists(fp):
            sheet.paste(Image.open(fp).convert("RGB").resize((CW, CW)), (x0 + j * CW, y0))
    pri_col = {"P1": (255, 179, 71), "P2": (134, 194, 74), "P3": (150, 170, 200)}[p["priority"]]
    d.text((x0, y0 + CW + 3), p["name"], font=f1, fill=(240, 240, 240))
    sz = "x".join(f"{v:g}" for v in [round(s, 1) for s in p["bbox_size_studs"]])
    d.text((x0, y0 + CW + 22), f"{p['priority']}  {','.join(p['holes'])}  {sz} st  {p['triangles']} tris"
           + ("  MOVING" if p["kind"] == "moving" else ""), font=f2, fill=pri_col)
sheet.save(os.path.join(OUT, "contact_sheet.png"))

