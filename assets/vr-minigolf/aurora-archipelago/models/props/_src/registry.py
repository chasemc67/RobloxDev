"""Prop registry: every generator registers itself with metadata used for the manifest/README."""

PROPS = []


def prop(name, holes, priority, *, target=None, kind="static", placements=None, motion=None, notes="",
         origin="base centre (bbox x/z centre, bottom)", front="+Z (Roblox); yaw it to face the player",
         smooth_angle=40, group="", variants=None, view=None, extra=None, previews_fn=None):
    """target: props.md size [x, y, z] studs (Roblox Y-up). placements: list of dicts
    {hole, pos:[x,y,z] hole-local position for the ORIGIN, yaw:deg, scale?, note?}.
    motion (moving parts): {type, axis_roblox, speed, units, range, course_local_pivot}."""
    def deco(fn):
        PROPS.append(dict(name=name, holes=holes, priority=priority, target=target, kind=kind,
                          placements=placements or [], motion=motion, notes=notes, origin=origin, front=front,
                          smooth_angle=smooth_angle, group=group, variants=variants, view=view, fn=fn,
                          extra=extra, previews_fn=previews_fn))
        return fn
    return deco


# pass 7b: prop categories inside the 'nature' group. 'plant' = living ground plants (grass, ferns, bushes, mushroom
# clumps, glowing shrooms / roots, saplings): every dressing instance of these keeps its WHOLE mesh footprint (XZ) >=
# PLANT_RAIL_CLEAR studs from every rail / collision wall of every hole (playtest: tall grass clipped the H1 rails).
# Trees are 'tree' (their trunks + everything below eye height already stay >= 3 from rails; the canopy is meant to
# overhang), rocks / leaf litter / fireflies / signs are not plants.
PLANT_RAIL_CLEAR = 1.5
CATEGORY = dict(
    plant=("grass_tuft", "fern_clump", "fern_clump_large", "red_leaf_bush", "orange_leaf_bush", "gold_leaf_bush",
           "red_bush_tall", "toadstool_cluster", "toadstool_tall", "toadstool_orange_cluster", "toadstool_trio_small",
           "glowing_mushrooms", "glow_shroom_patch", "glow_root_arch", "maple_sapling"),
    tree=("red_maple_tree", "golden_birch_tree", "maple_tree_round", "maple_tree_tall", "oak_tree_orange",
          "maple_tree_lanterns", "maple_tree_overhang", "tree_backdrop_cluster"),
    rock=("mossy_boulder", "rock_outcrop", "stepping_stones"),
    litter=("leaf_pile", "leaf_pile_wide", "leaf_scatter"),
    fauna=("firefly_cluster_low", "firefly_swarm"),
)
_CAT = {n: c for c, ns in CATEGORY.items() for n in ns}


def category(name):
    if name.startswith("treeline_card"):
        return "card"
    return _CAT.get(name, "structure")


def manifest_entry(p):
    e = dict(name=p["name"], group=p["group"], category=category(p["name"]), holes=p["holes"], priority=p["priority"], kind=p["kind"],
             origin=p["origin"], front=p["front"], target_size_props_md=p["target"], placements=p["placements"],
             notes=p["notes"])
    if p["motion"]:
        e["motion"] = p["motion"]
    if p["variants"]:
        e["variants"] = p["variants"]
    if p.get("extra"):              # pass 10: prop-specific manifest fields (e.g. vr_wrist_bracer.vr_attach)
        e.update(p["extra"])
    return e


def textures_block():
    import lglib
    return dict(
        dir="textures/",
        size="512x512 PNG, seamlessly tiling, sRGB (generated by _src/textures.py)",
        uv="box (cube) projection in prop space; 1 repeat per tile_studs; side faces map V to height",
        roblox=("One texture per MeshPart (each <prop>__<Material> child is one MeshPart). Either add a "
                "SurfaceAppearance with ColorMap = the uploaded PNG (keeps Material for sound/physics, best look), or set "
                "MeshPart.TextureID. Keep MeshPart.Color = the flat colour as a fallback / LOD tint."),
        materials={m: dict(texture=f"textures/{t}.png", tile_studs=k) for m, (t, k) in lglib.TEX.items()},
        untextured=sorted(m for m in lglib.MATS if m not in lglib.TEX),
    )


