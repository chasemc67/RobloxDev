#!/usr/bin/env python3
"""Sugarloaf Canyon (second course) data for Studio, stage w.

  python3 tools/sugarloaf_to_lua.py                 # write CourseData/SugarloafCanyon.luau + SugarloafLayout.luau
  python3 tools/sugarloaf_to_lua.py --push          # ...and copy both into Studio (Edit)
  python3 tools/sugarloaf_to_lua.py --terrain-grid  # ...and write sugarloaf-canyon/world/terrain-4stud.json

Sugarloaf is built next to Lantern Grove in the same place, shifted by OFFSET (all of its world.json / holes.json
world coordinates + OFFSET), into workspace.CourseSugarloaf (CourseBuilder.Build(data, layout, {folder = ...})).
The layout module carries the shifted hole placements, bounds, spawn, teleport points and lighting.
"""
import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from holes_to_lua import REPO, GAME_DIR, convert, to_lua  # noqa: E402

SC = os.path.join(REPO, "assets", "vr-mini-golf", "sugarloaf-canyon")
SPEC = os.path.join(SC, "holes.json")
WORLD = os.path.join(SC, "world", "world.json")
OUT_HOLES = os.path.join(GAME_DIR, "src", "ServerStorage", "CourseData", "SugarloafCanyon.luau")
OUT_LAYOUT = os.path.join(GAME_DIR, "src", "ServerStorage", "CourseData", "SugarloafLayout.luau")
GRID = os.path.join(SC, "world", "terrain-4stud.json")

# 5000 studs north of Lantern Grove (its terrain is x -360..440, z -400..400; backdrop cards reach |z| ~1950;
# the lobby is at z ~6000). Sugarloaf's terrain is x -640..640, z -640..640 -> world z -5640..-4360.
OFFSET = [0.0, 0.0, -5000.0]


def shift(p):
    return [p[0] + OFFSET[0], p[1] + OFFSET[1], p[2] + OFFSET[2]]


def layout():
    w = json.load(open(WORLD))
    holes = json.load(open(SPEC))["holes"]
    b = w["bounds"]
    out = {
        "course": "sugarloaf_canyon",
        "enabled": True,
        "offset": OFFSET,
        "bounds": {"x": [b["x"][0] + OFFSET[0], b["x"][1] + OFFSET[0]], "z": [b["z"][0] + OFFSET[2], b["z"][1] + OFFSET[2]],
                   "y_range": b["y_range"]},
        "holes": {},
        "spawn": {"pos": shift(w["spawn"]["pos"]), "look_at": shift(w["spawn"]["look_at"])},
        "teleport_points": [{"id": t["id"], "name": t["name"], "pos": shift(t["pos"])} for t in w["teleport_points"]],
        "sun": w["sun"],
        "source": {"world": os.path.relpath(WORLD, REPO), "version": w.get("version")},
    }
    for h in holes:
        out["holes"][h["number"]] = {"origin": shift(h["world_offset"]), "yaw": h["world_yaw"]}
    # Lua table keys for holes must be numbers: emit as an array (hole n at index n)
    out["holes"] = [out["holes"][n] for n in range(1, len(holes) + 1)]
    return out


def terrain_grid(cell=4):
    import numpy as np
    sys.path.insert(0, os.path.join(SC, "world", "tools"))
    import worldlib as wl  # noqa: E402
    w = wl.load_world()
    b = w["bounds"]
    xs = np.arange(b["x"][0] + cell / 2, b["x"][1], cell)
    zs = np.arange(b["z"][0] + cell / 2, b["z"][1], cell)
    X, Z = np.meshgrid(xs, zs)
    st = wl.height_at(w, X, Z, stages=True)
    H = st["final"]
    surf = st["water_surface"]
    # materials: 0 floor sand, 1 cliff sandstone (steep), 2 mesa-top sand, 3 walkway (graded paths), 4 water bed,
    # 5 dune sugar (H15 Sugar Dune, Hoodoo Bench)
    gz, gx = np.gradient(H, cell)
    slope = np.degrees(np.arctan(np.hypot(gx, gz)))
    mat = np.where(H > 60, 2, 0)
    pathed = np.abs(st["paths"] - st["pads"]) > 0.05
    mat = np.where(pathed, 3, mat)
    mat = np.where(slope > 35, 1, mat)
    wet = ~np.isnan(surf) & (surf > H + 0.05)
    mat = np.where(wet, 4, mat)
    for hz in [h for h in json.load(open(SPEC))["holes"] if h["number"] == 15]:
        ox, _, oz = hz["world_offset"]
        dune = (np.abs(X - ox) < 26) & (np.abs(Z - (oz + 30)) < 30) & (slope < 35)
        mat = np.where(dune, 5, mat)
    rows = len(zs)
    return {
        "note": "Sugarloaf Canyon terrain, 4-stud cells, row-major, row 0 = north. Course-local coordinates (add the "
                "layout offset). height = surface y, water = water surface y or null, mat = index (0 floor, 1 cliff, "
                "2 mesa top, 3 walkway, 4 water bed, 5 dune). Generated by games/vr-mini-golf/tools/sugarloaf_to_lua.py "
                "from world.json via world/tools/worldlib.height_at.",
        "x0": float(b["x"][0]), "z0": float(b["z"][0]), "cell": cell, "cols": len(xs), "rows": rows,
        "height": [[round(float(v), 2) for v in r] for r in H],
        "water": [[None if np.isnan(v) or not wv else round(float(v), 2) for v, wv in zip(r, wr)] for r, wr in zip(surf, wet)],
        "mat": [[int(v) for v in r] for r in mat],
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--push", action="store_true")
    ap.add_argument("--terrain-grid", action="store_true")
    args = ap.parse_args()
    src, data = convert(SPEC)
    # Optional motion overrides; stage af removed the H11 inversion so holes.json governs.
    overrides_path = os.path.join(HERE, "sugarloaf_motion_overrides.json")
    overrides = json.load(open(overrides_path))
    for hole in data["holes"]:
        by_id = overrides["holes"].get(str(hole["number"]), {})
        for mover in hole.get("moving_parts", []):
            mover.update(by_id.get(mover["id"], {}))
    data["source"]["motionOverrides"] = overrides
    src = src.split("return ", 1)[0] + "-- Motion overrides: tools/sugarloaf_motion_overrides.json\nreturn " + to_lua(data) + "\n"
    open(OUT_HOLES, "w").write(src.replace("tools/holes_to_lua.py --push --build",
                                           "tools/sugarloaf_to_lua.py --push; CourseBuilder.Build into CourseSugarloaf"))
    lay = layout()
    head = ("-- GENERATED by games/vr-mini-golf/tools/sugarloaf_to_lua.py from %s.\n"
            "-- Sugarloaf Canyon placement in this place: every world.json/holes.json world coordinate + offset.\n"
            % os.path.relpath(WORLD, REPO))
    open(OUT_LAYOUT, "w").write(head + "return " + to_lua(lay) + "\n")
    print("wrote", os.path.relpath(OUT_HOLES, GAME_DIR), "and", os.path.relpath(OUT_LAYOUT, GAME_DIR),
          "(%d holes, par %d)" % (len(data["holes"]), sum(h["par"] for h in data["holes"])))
    if args.terrain_grid:
        g = terrain_grid()
        json.dump(g, open(GRID, "w"), separators=(",", ":"))
        print("wrote", os.path.relpath(GRID, REPO), g["cols"], "x", g["rows"])
    if args.push:
        import run_playtests as rp  # noqa: E402
        st = rp.Studio()
        if st.mode()[0] != "Edit":
            raise SystemExit("stop play first")
        rp.cmd_push(argparse.Namespace(files=[OUT_HOLES, OUT_LAYOUT]), st)


if __name__ == "__main__":
    main()
