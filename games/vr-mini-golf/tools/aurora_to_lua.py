#!/usr/bin/env python3
"""Generate Aurora course data and world placement, with no course offset."""
import os
from holes_to_lua import REPO, GAME_DIR, convert, to_lua

SPEC = os.path.join(REPO, "assets/vr-mini-golf/aurora-archipelago/holes.json")
OUT = os.path.join(GAME_DIR, "src/ServerStorage/CourseData")

def main():
    source, data = convert(SPEC)
    source = source.replace("tools/holes_to_lua.py --push --build", "tools/aurora_to_lua.py")
    assert len(source) < 200000, "Split data before pushing: Studio Source limit"
    with open(os.path.join(OUT, "AuroraArchipelago.luau"), "w") as f:
        f.write(source)
    layout = {"course": "aurora_archipelago", "enabled": True, "offset": [0, 0, 0],
              "holes": [{"origin": h["world_offset"], "yaw": h.get("world_yaw", 0)} for h in data["holes"]]}
    with open(os.path.join(OUT, "AuroraLayout.luau"), "w") as f:
        f.write("-- GENERATED by tools/aurora_to_lua.py; holes.json world coordinates, no offset.\nreturn " + to_lua(layout) + "\n")
    print("Aurora:", len(data["holes"]), "holes;", len(source), "characters")

if __name__ == "__main__":
    main()
