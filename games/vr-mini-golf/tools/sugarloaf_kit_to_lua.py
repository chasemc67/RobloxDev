#!/usr/bin/env python3
"""Convert the Sugarloaf Canyon world kit manifest (pass 6) into the SugarloafKit ModuleScript.

  python3 tools/sugarloaf_kit_to_lua.py            # write src/ServerStorage/CourseData/SugarloafKit.luau
  python3 tools/sugarloaf_kit_to_lua.py --push     # ...and copy it into the open Studio

Per FBX file (= the Model the 3D Importer makes from one top-level Empty of the merged FBX): each mesh's
centre from the piece origin and size (Roblox axes, studs), Roblox material, colour, whether it's textured,
CastShadow and transparency. Per piece: its files and its instances (pos = origin in Sugarloaf world coords,
yaw, optional per-axis scale). Plus the gondola cabin's motion (two parabolic spans per line).
Read by ServerStorage.SugarloafBuilder (PrepareKit / PlaceKit / gondola). The merged FBX for the importer are
assets/vr-mini-golf/sugarloaf-canyon/models/fbx/kit_merged_pass6/sugarloaf_kit_pass6_{a,b,c}.fbx
(tools/merge_fbx_for_import.py).
"""
import argparse
import hashlib
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from holes_to_lua import GAME_DIR, REPO, to_lua  # noqa: E402

MODELS = os.path.join(REPO, "assets", "vr-mini-golf", "sugarloaf-canyon", "models")
DEFAULT_OUT = os.path.join(GAME_DIR, "src", "ServerStorage", "CourseData", "SugarloafKit.luau")


def r3(v):
    return [round(float(x), 3) for x in v]


def convert():
    path = os.path.join(MODELS, "manifest.json")
    raw = open(path, "rb").read()
    man = json.loads(raw)
    files, pieces = {}, {}
    for p in man["pieces"]:
        stems = []
        for part in p["parts"]:
            stem = os.path.splitext(os.path.basename(part["file"].replace("\\", "/")))[0]
            stems.append(stem)
            meshes = {}
            for m in part["meshes"]:
                e = {"c": r3(m["bbox_center_from_origin"]), "s": r3(m["size"]), "mat": m["roblox_material"],
                     "color": m["color"], "tex": bool(m.get("texture"))}
                if m.get("cast_shadow") is False:
                    e["noShadow"] = True
                if m.get("transparency"):
                    e["tr"] = m["transparency"]
                meshes[m["mesh"]] = e
            files[stem] = {"group": p["group"], "meshes": meshes}
        inst = []
        for i in p["instances"]:
            e = {"pos": r3(i["pos"]), "yaw": round(float(i.get("yaw", 0)), 3)}
            s = i.get("scale")
            if s not in (None, 1, [1, 1, 1]):
                e["scale"] = r3(s) if isinstance(s, list) else [float(s)] * 3
            inst.append(e)
        pieces[p["id"]] = {"group": p["group"], "files": stems, "instances": inst}
        if p.get("motion"):
            mo = p["motion"]
            def line(d, sags=(10.0, 2.5)):
                return {"A": r3(d["A_bottom_attach"]), "T": r3(d["T_tower_crest"]), "B": r3(d["B_top_attach"]),
                        "arcs": r3(d["span_arc_lengths"]), "sags": list(sags)}
            pieces[p["id"]]["motion"] = {"speed": mo["speed_studs_s"], "up": line(mo["up_line"]),
                                         "down": line(mo["down_line"]), "upYaw": 53.53, "downYaw": 233.53}
    sha = hashlib.sha1(raw).hexdigest()
    # Studio caps a script's Source at 200,000 characters: the per-file mesh table goes into SugarloafKitFiles<N>
    # chunk modules (merged by the main module through absolute paths, since the builders require a Clone).
    chunks, cur = [], {}
    for stem in sorted(files):
        cur[stem] = files[stem]
        if len(to_lua(cur)) > 120000:
            chunks.append(cur)
            cur = {}
    if cur:
        chunks.append(cur)
    out = {"source": {"file": os.path.relpath(path, REPO), "sha1": sha}, "fileChunks": len(chunks), "pieces": pieces}
    head = ("-- GENERATED by games/vr-mini-golf/tools/sugarloaf_kit_to_lua.py from the Sugarloaf Canyon kit manifest, "
            "pass 6 (sha1 %s).\n-- Read by ServerStorage.SugarloafBuilder (PrepareKit / PlaceKit). Positions are "
            "Sugarloaf world coords (add SugarloafLayout.offset).\n" % sha[:12])
    main = (head + "local KIT = " + to_lua(out) + "\n"
            "KIT.files = {}\n"
            "for i = 1, KIT.fileChunks do\n"
            "\tfor stem, f in require(game:GetService(\"ServerStorage\").CourseData[\"SugarloafKitFiles\" .. i]:Clone()) do\n"
            "\t\tKIT.files[stem] = f\n\tend\nend\nreturn KIT\n")
    parts = [(head + "-- chunk %d of %d of SugarloafKit.files\nreturn " % (i + 1, len(chunks)) + to_lua(c) + "\n") for i, c in enumerate(chunks)]
    return main, parts


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--push", action="store_true")
    a = ap.parse_args()
    main, parts = convert()
    outs = [a.out]
    with open(a.out, "w") as f:
        f.write(main)
    d = os.path.dirname(a.out)
    for old in os.listdir(d):
        if old.startswith("SugarloafKitFiles"):
            os.remove(os.path.join(d, old))
    for i, text in enumerate(parts):
        p = os.path.join(d, "SugarloafKitFiles%d.luau" % (i + 1))
        with open(p, "w") as f:
            f.write(text)
        outs.append(p)
    for p in outs:
        print("wrote", p, os.path.getsize(p), "bytes")
    if a.push:
        subprocess.check_call([sys.executable, os.path.join(HERE, "run_playtests.py"), "push"] + outs)


if __name__ == "__main__":
    main()
