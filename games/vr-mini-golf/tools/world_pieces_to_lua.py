#!/usr/bin/env python3
"""Convert 3D Model Bot's world-piece manifest (models/world/manifest.json) into the WorldPieces ModuleScript.

  python3 tools/world_pieces_to_lua.py            # write src/ServerStorage/CourseData/WorldPieces.luau
  python3 tools/world_pieces_to_lua.py --push     # ...and copy it into Studio

Contents per piece: kind, the FBX files (= the Model names the 3D Importer creates), per-mesh material
(Color/Material/Transparency) and bbox centre relative to the piece origin (to recover the origin and the importer's
yaw), and the world instances (pos = origin in world studs, yaw, scale). Also the H9 interior PointLight spots
(models/manifest.json > world.h9_interior_lights). Read by ServerStorage.WorldBuilder.PrepareWorldLibrary/PlaceWorldPieces.
Import: models/world/fbx/*.fbx with Studio's 3D Importer (tools/codex_ui.sh + logs/prompts/import_world_c.md).
"""
import argparse
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from holes_to_lua import GAME_DIR, REPO, to_lua  # noqa: E402

MODELS = os.path.join(REPO, "assets", "vr-mini-golf", "lantern-grove", "models")
DEFAULT_OUT = os.path.join(GAME_DIR, "src", "ServerStorage", "CourseData", "WorldPieces.luau")


def r3(v):
    return [round(float(x), 3) for x in v]


def convert():
    path = os.path.join(MODELS, "world", "manifest.json")
    raw = open(path, "rb").read()
    man = json.loads(raw)
    props = json.load(open(os.path.join(MODELS, "manifest.json")))
    out = {"source": {"file": os.path.relpath(path, REPO), "sha1": hashlib.sha1(raw).hexdigest()}, "pieces": {}}
    for p in man["pieces"]:
        files = {}
        for part in p["parts"]:
            fname = os.path.splitext(os.path.basename(part["file"]))[0]
            meshes = {}
            for m in part["meshes"]:
                meshes[m["mesh"]] = {"color": m["color"], "material": m["roblox_material"],
                                     "transparency": m.get("transparency", 0), "center": r3(m["bbox_center_from_origin"]),
                                     "size": r3(m["size"])}
            files[fname] = {"center": r3(part["bbox_center_from_origin"]), "size": r3(part["bbox_size_studs"]),
                            "meshes": meshes}
        inst = []
        for i in p["instances"]:
            e = {"pos": r3(i["pos"]), "yaw": round(float(i.get("yaw", 0)), 2), "wid": i.get("world_json_id")}
            if "scale" in i:
                s = i["scale"]
                e["scale"] = r3(s) if isinstance(s, list) else [float(s)] * 3
            inst.append(e)
        out["pieces"][p["id"]] = {"kind": p["kind"], "files": files, "instances": inst, "tris": p["tris"]}
    lights = props.get("world", {}).get("h9_interior_lights", {})
    out["h9InteriorLights"] = [{"kind": l["kind"], "pos": r3(l["pos"])} for l in lights.get("lights", [])]
    head = ("-- GENERATED by games/vr-mini-golf/tools/world_pieces_to_lua.py from the 3D Model Bot world manifest (sha1 %s).\n"
            "-- Read by ServerStorage.WorldBuilder (PrepareWorldLibrary / PlaceWorldPieces). Positions are world studs.\n"
            % out["source"]["sha1"][:12])
    return head + "return " + to_lua(out) + "\n", out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--push", action="store_true")
    args = ap.parse_args()
    src, data = convert()
    with open(args.out, "w") as fh:
        fh.write(src)
    n = sum(len(p["instances"]) for p in data["pieces"].values())
    print("wrote %s (%d bytes, %d pieces, %d instances, %d H9 lights)" % (
        os.path.relpath(args.out, GAME_DIR), len(src), len(data["pieces"]), n, len(data["h9InteriorLights"])))
    if args.push:
        import run_playtests as rp  # noqa: E402
        st = rp.Studio()
        rp.cmd_push(argparse.Namespace(files=[args.out]), st)


if __name__ == "__main__":
    main()
